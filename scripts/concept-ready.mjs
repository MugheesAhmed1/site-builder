// Lists the scene-concept pictures that exist in public/real/concepts, so concepts.js only
// offers concepts whose pictures have all been made. Run after adding pictures; prebuild runs it too.
import { readdirSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const root = join(process.cwd(), "public/real/concepts");
const files = [];
if (existsSync(root))
  for (const dir of readdirSync(root).sort())
    for (const f of readdirSync(join(root, dir)).sort()) if (f.endsWith(".webp")) files.push(`/real/concepts/${dir}/${f}`);
writeFileSync(
  join(process.cwd(), "template/src/concepts-ready.js"),
  "// Generated by scripts/concept-ready.mjs: the scene-concept pictures that exist.\nexport const READY_FILES = " + JSON.stringify(files, null, 2) + ";\n"
);
console.log(`Concept pictures ready: ${files.length}`);
