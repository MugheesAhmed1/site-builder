// Renders every scene once, through the real engine, into the small pictures the pickers show
// (public/scenes/thumbs) and records each scene's flat colour (template/src/atmos/flats.js),
// which scenes blend into and out of. Run with the dev server up:
//   npm run dev -- -p 3100 & node scripts/scene-thumbs.mjs
import { createRequire } from "node:module";
const { chromium } = createRequire(import.meta.url)("playwright");
import { writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { SCENES } from "../template/src/atmos/catalog.js";

const BASE = process.env.LAB || "http://localhost:3100";
const only = process.argv.slice(2);
const list = only.length ? SCENES.filter((s) => only.includes(s.id)) : SCENES;
const b = await chromium.launch({ args: ["--use-gl=angle", "--use-angle=swiftshader", "--ignore-gpu-blocklist", "--enable-unsafe-swiftshader"] });
// A fresh page per scene: software WebGL is slow, and each scene gets its own first frame.
for (const s of list) {
  const p = await b.newPage({ viewport: { width: 640, height: 400 } });
  await p.goto(BASE + "/lab/scene?n=7&gpu=1&id=" + s.id, { waitUntil: "load", timeout: 60000 });
  await p.waitForTimeout(Number(process.env.WAIT || 3500));
  await p.screenshot({ path: `/tmp/scene-${s.id}.png` });
  await p.close();
  process.stdout.write(s.id + " ");
}
await b.close();
// Resize, encode and average with Python's Pillow (always present where this runs).
const py = `
import json,sys
from PIL import Image
ids=json.loads(sys.argv[1]); stills=set(json.loads(sys.argv[2])); out={}
for i in ids:
  im=Image.open(f'/tmp/scene-{i}.png').convert('RGB')
  im.resize((320,200),Image.LANCZOS).save(f'public/scenes/thumbs/{i}.webp','WEBP',quality=72,method=6)
  # Scenes without a photo of their own get a poster: the still shown without a graphics card.
  if i in stills: im.save(f'public/scenes/posters/{i}.webp','WEBP',quality=74,method=6)
  r,g,b=im.resize((1,1),Image.BOX).getpixel((0,0))
  out[i]='#%02x%02x%02x'%(r,g,b)
print(json.dumps(out))
`;
const flats = JSON.parse(execFileSync("python3", ["-c", py, JSON.stringify(list.map((s) => s.id)), JSON.stringify(list.filter((s) => s.family !== "plate").map((s) => s.id))], { encoding: "utf8" }));
const { FLATS } = await import("../template/src/atmos/flats.js");
const all = { ...FLATS, ...flats };
writeFileSync("template/src/atmos/flats.js", "// The flat colour of every scene, which it blends into and out of. Generated by\n// scripts/scene-thumbs.mjs from the scene's own picture.\nexport const FLATS = " + JSON.stringify(all, null, 2) + ";\n");
console.log("\nDone:", list.length, "scenes");
