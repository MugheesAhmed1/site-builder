// Copies the portfolio template's source files into lib/template-files.ts so the
// builder can put them into the downloadable zip. Runs automatically before dev and build.
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const root = new URL("../template/", import.meta.url).pathname;
const files = {};
function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else files[relative(root, p)] = readFileSync(p, "utf8");
  }
}
walk(root);
const out = `// Generated by scripts/bundle-template.mjs. Do not edit by hand.\nexport const TEMPLATE_FILES: Record<string, string> = ${JSON.stringify(files, null, 2)};\n`;
writeFileSync(new URL("../lib/template-files.ts", import.meta.url), out);
console.log("Bundled", Object.keys(files).length, "template files");
