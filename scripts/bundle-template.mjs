// Copies the portfolio template's source files into lib/template-files.ts so the
// builder can put them into the downloadable zip. Runs automatically before dev and build.
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";

// Only what the site actually runs goes into the download: the project files at the top of
// the template, then every source file reachable from src/main.tsx through its imports.
const root = new URL("../template/", import.meta.url).pathname;
const files = {};
for (const name of readdirSync(root)) {
  const p = join(root, name);
  if (statSync(p).isFile()) files[name] = readFileSync(p, "utf8");
}
const EXT = ["", ".ts", ".tsx", ".js", ".jsx", "/index.ts", "/index.tsx", "/index.js"];
const seen = new Set();
function visit(file) {
  if (seen.has(file)) return;
  seen.add(file);
  const text = readFileSync(file, "utf8");
  files[relative(root, file)] = text;
  if (!/\.(m?[jt]sx?)$/.test(file)) return;
  for (const m of text.matchAll(/(?:import|export)\s[^"']*?from\s*["'](\.[^"']+)["']|import\s*\(?\s*["'](\.[^"']+)["']/g)) {
    const spec = m[1] || m[2];
    if (spec.endsWith("site-data.json")) continue;
    const base = resolve(dirname(file), spec);
    const hit = EXT.map((e) => base + e).find((p) => existsSync(p) && statSync(p).isFile());
    if (hit) visit(hit);
    else throw new Error("bundle-template: cannot resolve " + spec + " from " + relative(root, file));
  }
}
visit(join(root, "src/main.tsx"));
const out = `// Generated by scripts/bundle-template.mjs. Do not edit by hand.\nexport const TEMPLATE_FILES: Record<string, string> = ${JSON.stringify(files, null, 2)};\n`;
writeFileSync(new URL("../lib/template-files.ts", import.meta.url), out);
console.log("Bundled", Object.keys(files).length, "template files (reachable from src/main.tsx)");

// The résumé reader runs pdf.js in the browser; its worker must be served as a static file.
import { copyFileSync, mkdirSync } from "node:fs";
mkdirSync(new URL("../public/", import.meta.url), { recursive: true });
copyFileSync(new URL("../node_modules/pdfjs-dist/build/pdf.worker.min.mjs", import.meta.url), new URL("../public/pdf.worker.min.mjs", import.meta.url));
