import type { Beat, Behaviour, ExperienceMode, Interaction, Metaphor, Params, PerformanceTier, SceneKind, StageEngine2D, StageEngine3D } from "@/template/src/experiences/types";

// The visual concept library (PRD sections 4.3, 21, 22, 34 and 58 to 60). A concept is the one
// dominant creative idea a site is built around: a metaphor, a world, an anchor object that
// carries the story from scene to scene, and the beats of that story from first view to the
// call to action. The storyboard (storyboard.ts) maps these beats onto the site's content.
//
// Every concept here is original work: procedural visuals drawn by our own engines in
// template/src/scenes. No third-party code or assets are involved, so every one may ship in
// a downloaded site (licence "original", see packages/quality-engine/licences.ts).

/** PRD section 34. */
export interface ExperienceTemplate {
  id: string;
  name: string;
  description: string;
  category: "cinematic" | "interactive" | "editorial" | "playful" | "3d" | "product";
  compatibleIndustries: string[];
  motionIntensity: number;
  interactionTypes: string[];
  technologies: string[];
  performanceTier: PerformanceTier;
  mobileStrategy: string;
  reducedMotionStrategy: string;
  license: string;
  source: string;
}

export interface ConceptBeat {
  title: string;
  note: string;
  beat: Beat;
  /** The kind of scene this beat suits best; the storyboard prefers matching content here. */
  prefers?: SceneKind[];
}

export interface Concept extends ExperienceTemplate {
  /** The modes it works in, best first. */
  modes: ExperienceMode[];
  metaphor: Metaphor;
  world: string;
  engine: StageEngine2D;
  webgl?: StageEngine3D;
  params: Params;
  pitch: string;
  beats: ConceptBeat[];
  heroMechanic: string;
  transitionMechanic: string;
  visualAnchor: string;
  anchor: { type: string; behaviours: Behaviour[] };
  character?: { type: string; behaviours: Behaviour[] };
  /** Cursor, click and touch moments the concept offers; scroll is implied by the beats. */
  interactions: Interaction[];
  /** Words in a request or a site's content that point to this concept. */
  keywords: string[];
  /** Below this intensity the concept is too quiet to carry its idea. */
  minIntensity: number;
  flags: { scroll: boolean; object: boolean; webgl: boolean; character: boolean };
}

const ORIGINAL = { license: "original", source: "Site Builder (procedural, this repository)" };

const I = (input: Interaction["input"], target: string, primitive: string, response: string, touch?: string): Interaction => ({ input, target, primitive, response, touch });

type Draft = Omit<Concept, "license" | "source" | "flags" | "technologies" | "category"> & { category?: Concept["category"]; flags?: Partial<Concept["flags"]>; technologies?: string[] };

function C(d: Draft): Concept {
  const webgl = !!d.webgl;
  const canvas = !["interface", "ledger", "kinetic", "assemble"].includes(d.engine);
  const tech = d.technologies ?? ["css", "motion", ...(canvas ? ["canvas"] : ["svg"]), ...(d.motionIntensity >= 5 ? ["lenis"] : []), ...(webgl ? ["three", "r3f"] : [])];
  const category: Concept["category"] = d.category ?? (webgl ? "3d" : d.modes[0] === "product" ? "product" : d.modes[0] === "editorial" ? "editorial" : d.modes[0] === "playful" ? "playful" : d.modes[0] === "world" ? "interactive" : "cinematic");
  return {
    ...ORIGINAL,
    ...d,
    category,
    technologies: tech,
    flags: {
      scroll: d.beats.length >= 4,
      object: d.interactions.some((x) => x.input === "click" || x.input === "touch") && !!d.anchor,
      webgl,
      character: !!d.character,
      ...d.flags,
    },
  };
}

